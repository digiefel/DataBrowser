# Patterns expected to work; a check that the walk (with fixes) handles them. Run from the repo root:
#   julia --startup-file=no --project=bench research_notes/code-change-detection/R-review/r06_misc.jl
include(joinpath(@__DIR__, "harness.jl"))

# a. Default argument edited.
Core.eval(Main, :(smooth(v, w=3) = sum(v) / w; stage_a(v) = smooth(v)))
demo("a default argument edited", () -> stage_a([3.0]), () -> [stage_a], :(smooth(v, w=5) = sum(v) / w))

# b. Module B extends a function of user module A; edit B's method. MISSED: the qualified call
#    `ModA.fitline(t)` lowers to `getproperty(ModA, :fitline)`, so no GlobalRef names `fitline`.
# (was: Module B extends a function of user module A; edit B's method.
Core.eval(Main, :(module ModA; fitline(x) = x; end))
Core.eval(Main, :(module ModB; import ..ModA; struct T; x::Float64; end; ModA.fitline(t::T) = t.x; end))
Core.eval(Main, :(stage_b(t) = ModA.fitline(t)))
demo("b method in ModB on ModA.fitline edited", () -> stage_b(ModB.T(2.0)), () -> [stage_b],
    :(@eval ModB ModA.fitline(t::T) = 2t.x))

# c. Functions generated by a macro/@eval loop.
include_string(Main, raw"""
    for (name, k) in ((:scale_mv, 1e-3), (:scale_ua, 1e-6)); @eval $name(x) = $k * x; end
    stage_c(x) = scale_mv(x)
""")
demo("c @eval-generated function regenerated", () -> stage_c(1.0), () -> [stage_c], :(scale_mv(x) = 1e-2 * x))

# d. Closures created in a loop, registered as callbacks; the loop is re-run with new values.
Core.eval(Main, quote
    const CBS = Dict{Symbol,Function}()
    for (kind, f) in (:iv => 1.0, :rt => 2.0); CBS[kind] = x -> f * x; end
    stage_d = CBS[:iv]
end)
demo("d loop-made closure, loop re-run with new factor", () -> Main.stage_d(1.0), () -> [Main.stage_d],
    :(for (kind, f) in (:iv => 3.0,); CBS[kind] = x -> f * x; end; stage_d = CBS[:iv]))

# e. The same helper file included twice (two scripts include common.jl): no change expected.
Core.eval(Main, :(fmt(x) = round(x; digits=2); stage_e(x) = fmt(x)))
demo("e same definitions included again (no change)", () -> stage_e(1.234), () -> [stage_e],
    :(fmt(x) = round(x; digits=2)))

# f. Plain qualified call into a user submodule (or a dev package): `MyLab.fit(x)`.
Core.eval(Main, :(module MyLab; fit(x) = 2x; end))
Core.eval(Main, :(stage_f(x) = MyLab.fit(x)))
demo("f qualified call MyLab.fit(x); fit edited", () -> stage_f(1.0), () -> [stage_f],
    :(@eval MyLab fit(x) = 3x))
